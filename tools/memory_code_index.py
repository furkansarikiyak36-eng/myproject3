"""Regenerates memory/CODE_INDEX.md: every C++ unit with line counts, types, enums and UFUNCTIONs.

Run from anywhere: python tools/memory_code_index.py   (no Unreal needed)
"""
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "Source", "MyProject3")
OUT = os.path.join(ROOT, "memory", "CODE_INDEX.md")

# Type definitions only (skip forward declarations like "class AFoo;").
TYPE_RE = re.compile(r"^\s*(?:class|struct)\s+(?:\w+_API\s+)?([AUFIE]\w+)\b(?!\s*;)", re.M)
ENUM_RE = re.compile(r"enum\s+class\s+(\w+)\s*:\s*\w+\s*\{([^}]*)\}", re.S)
FUNC_RE = re.compile(r"UFUNCTION\([^)]*\)\s*(?:static\s+|virtual\s+)?[\w<>:,\s\*&]+?\b(\w+)\s*\(")


def clean(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return re.sub(r'UMETA\((?:[^()"]|"[^"]*")*\)', "", text)


def rel(path):
    return os.path.relpath(path, ROOT).replace("\\", "/")


def main():
    rows = {}
    for folder, _, files in os.walk(SRC):
        for name in sorted(files):
            if not name.endswith((".h", ".cpp")):
                continue
            path = os.path.join(folder, name)
            base = os.path.splitext(rel(path))[0].replace("Source/MyProject3/", "")
            raw = open(path, encoding="utf-8", errors="ignore").read()
            row = rows.setdefault(base, {"h": 0, "cpp": 0, "types": [], "enums": [], "funcs": []})
            row["h" if name.endswith(".h") else "cpp"] = raw.count("\n") + 1
            if name.endswith(".h"):
                text = clean(raw)
                row["types"] += TYPE_RE.findall(text)
                for enum_name, values in ENUM_RE.findall(text):
                    items = [v.split("=")[0].strip() for v in values.split(",") if v.strip()]
                    row["enums"].append(f"{enum_name}{{{', '.join(items)}}}")
                row["funcs"] += FUNC_RE.findall(text)

    try:
        commit = subprocess.check_output(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], text=True).strip()
    except Exception:
        commit = "?"

    lines = [
        "# Code index (generated)",
        "",
        f"Generated by `tools/memory_code_index.py` at commit `{commit}`. Do not edit by hand; rerun the script.",
        "Meaning, status and plan links are in `CODEBASE.md`; this file is the raw list.",
        "",
        "| Unit (Source/MyProject3/) | .h | .cpp | Types | Enums | UFUNCTIONs |",
        "|---|---:|---:|---|---|---|",
    ]
    for base in sorted(rows):
        row = rows[base]
        lines.append(
            f"| `{base}` | {row['h'] or ''} | {row['cpp'] or ''} | "
            f"{', '.join(dict.fromkeys(row['types']))} | {'; '.join(row['enums'])} | "
            f"{', '.join(dict.fromkeys(row['funcs']))} |"
        )
    total = sum(r["h"] + r["cpp"] for r in rows.values())
    lines += ["", f"Total: {len(rows)} units, {total} lines."]
    with open(OUT, "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")
    print(f"{rel(OUT)}: {len(rows)} units, {total} lines")


if __name__ == "__main__":
    main()
